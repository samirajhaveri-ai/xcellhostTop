/** Shared destination rules for header navigation and website search. */
export function menuItemLink(title: string, menu: string, catalog: CatalogService, explicitLink?: string): string {
  if (explicitLink) return explicitLink;
  if (CONTENT_LINKS[title]) return CONTENT_LINKS[title];
  if (menu === 'Insights' || menu === 'Company') return '/under-construction/' + slugify(title);
  const entry = catalog.findInDirectory(title);
  const slug = slugify(entry ? entry.name : title);
  return catalog.entryBySlug(slug) ? '/' + slug : '/under-construction/' + slugify(title);
}
