(function () {
  const main = document.querySelector('main');
  if (!main) return;
  const selector = 'h1,h2,h3,h4,.sz-eb,.sz-ebc,.sz-hb .h2,.sg-eb,.sg-ebc,.sg-hb .h2,.sg-h2,.sa-eb,.sa-ebc,.sa-hb .h2,.sa-h2,.sd-eb,.sd-ebc,.se-eb,.se-ebc,.pr-r .pn b';
  let pending = false;
  function fit() {
    pending = false;
    main.querySelectorAll(selector).forEach(function (heading) {
      heading.style.removeProperty('font-size');
      const style = getComputedStyle(heading);
      const available = heading.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight);
      if (available <= 0) return;
      const range = document.createRange();
      range.selectNodeContents(heading);
      const width = range.getBoundingClientRect().width;
      if (width > available) {
        const size = parseFloat(style.fontSize) * (available - 1) / width;
        heading.style.setProperty('font-size', size + 'px', 'important');
      }
    });
  }
  function schedule() {
    if (pending) return;
    pending = true;
    requestAnimationFrame(fit);
  }
  window.addEventListener('resize', schedule);
  main.addEventListener('click', schedule);
  document.fonts.ready.then(schedule);
  // Pricing rows and other section headings can be generated by the page tools.
  const observer = new MutationObserver(function (records) {
    if (records.some(function (record) {
      return record.target.closest?.(selector) || Array.from(record.addedNodes).some(function (node) {
        return node.nodeType === 1 && (node.matches(selector) || node.querySelector(selector));
      });
    })) schedule();
  });
  observer.observe(main, { childList: true, subtree: true, characterData: true });
  schedule();
})();
